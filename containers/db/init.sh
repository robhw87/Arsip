set -e

DB_HOST="${DB_HOST:-127.0.0.1}"
DB_PORT="${DB_PORT:-5432}"

# until pg_isready -h 127.0.0.1 -p 5432 -U "$POSTGRES_USER" -d "$POSTGRES_DB"; do
until pg_isready; do
  echo "Waiting for database at $DB_HOST:$DB_PORT..."
  sleep 2
done
echo "Running initiation database"
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER $MIGRATOR WITH PASSWORD '$MIGRATOR_PASS';
    GRANT ALL PRIVILEGES ON DATABASE $POSTGRES_DB TO $MIGRATOR;
    GRANT ALL PRIVILEGES ON SCHEMA public TO $MIGRATOR;
    CREATE USER $APP_USER WITH PASSWORD '$APP_USER_PASS';
    ALTER DEFAULT PRIVILEGES FOR ROLE $APP_USER IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO $APP_USER;
EOSQL
