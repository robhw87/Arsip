CREATE SCHEMA IF NOT EXISTS cms;

CREATE TABLE IF NOT EXISTS cms.categories (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    CONSTRAINT categories_name_not_empty CHECK (length(name) > 0)
);

CREATE TABLE IF NOT EXISTS cms.tags (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    CONSTRAINT tags_name_not_empty CHECK (length(name) > 0)
);

CREATE TABLE IF NOT EXISTS cms.articles (
    slug           TEXT NOT NULL,
    language       TEXT NOT NULL,
    title          TEXT NOT NULL,
    body           TEXT NOT NULL,
    status         TEXT NOT NULL,
    filename       TEXT NULL,
    category_id    INTEGER NULL,
    publish_at     TIMESTAMPTZ NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    missing_since  TIMESTAMPTZ NULL,
    PRIMARY KEY (slug, language),
    CONSTRAINT articles_status_check CHECK (status IN ('draft', 'published', 'archived')),
    CONSTRAINT articles_language_check CHECK (language ~ '^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$'),
    CONSTRAINT articles_slug_check CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT articles_title_not_empty CHECK (length(title) > 0),
    CONSTRAINT articles_body_not_empty CHECK (length(body) > 0),
    CONSTRAINT articles_category_fk FOREIGN KEY (category_id)
    REFERENCES cms.categories (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS cms.aliases (
    alias        TEXT NOT NULL,
    language     TEXT NOT NULL,
    target_slug  TEXT NOT NULL,
    target_lang  TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (alias, language),
    CONSTRAINT aliases_alias_check CHECK (alias ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT aliases_language_check CHECK (language ~ '^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$'),
    CONSTRAINT aliases_target_fk FOREIGN KEY (target_slug, target_lang)
    REFERENCES cms.articles (slug, language) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS cms.article_tags (
    article_slug     TEXT NOT NULL,
    article_language TEXT NOT NULL,
    tag_id           INTEGER NOT NULL,
    PRIMARY KEY (article_slug, article_language, tag_id),
    CONSTRAINT article_tags_article_fk FOREIGN KEY (article_slug, article_language)
    REFERENCES cms.articles (slug, language) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT article_tags_tag_fk FOREIGN KEY (tag_id)
    REFERENCES cms.tags (id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Indexes
CREATE INDEX idx_articles_status ON cms.articles (status);
CREATE INDEX idx_articles_language ON cms.articles (language);
CREATE INDEX idx_articles_category ON cms.articles (category_id);
CREATE INDEX idx_articles_slug_trgm ON cms.articles USING GIN (slug gin_trgm_ops);
CREATE INDEX idx_slug_aliases_target ON cms.aliases (target_slug, target_lang);
CREATE INDEX idx_article_tags_tag ON cms.article_tags (tag_id);
